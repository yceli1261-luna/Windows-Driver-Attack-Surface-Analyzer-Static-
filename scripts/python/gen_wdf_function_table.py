"""Generate core/driver/WdfFunctionTable.cpp from a KMDF wdffuncenum.h.

KMDF client drivers call framework DDIs through a function table
(WdfFunctions_01xxx[WdfXxxTableIndex]), so the call sites contain an index,
not a name. This script turns the WDFFUNCENUM enum from Microsoft's public
header into the index -> name table DASA uses to label those calls.

Source header (MIT licensed, Copyright (c) Microsoft):
  https://github.com/microsoft/Windows-Driver-Frameworks/blob/main/src/publicinc/wdf/kmdf/1.33/wdffuncenum.h

The enum only ever grows by appending, so the 1.33 table also names the
indices used by drivers built against older KMDF versions.

Usage: python gen_wdf_function_table.py <wdffuncenum.h> <output .cpp>
"""
from __future__ import annotations

import re
import sys


def main() -> None:
    header, out_path = sys.argv[1], sys.argv[2]
    text = open(header, encoding="utf-8", errors="replace").read()
    body = text[text.index("typedef enum _WDFFUNCENUM"):]
    body = body[: body.index("} WDFFUNCENUM;")]
    entries = re.findall(r"(Wdf\w+)TableIndex\s*=\s*(\d+)", body)
    names = {int(i): n for n, i in entries}
    count = max(names) + 1
    missing = [i for i in range(count) if i not in names]
    if missing:
        raise SystemExit(f"non-contiguous enum, missing {missing[:10]}")

    lines = [
        "// Generated by scripts/python/gen_wdf_function_table.py from KMDF 1.33",
        "// wdffuncenum.h (github.com/microsoft/Windows-Driver-Frameworks, MIT",
        "// licence, Copyright (c) Microsoft). Do not edit by hand.",
        "",
        '#include "core/driver/WdfFunctionTable.h"',
        "",
        "namespace dasa::core::driver {",
        "",
        "namespace {",
        f"constexpr const char* kNames[{count}] = {{",
    ]
    lines += [f'    "{names[i]}", // {i}' for i in range(count)]
    lines += [
        "};",
        "} // namespace",
        "",
        "std::size_t wdfFunctionCount() {",
        f"    return {count};",
        "}",
        "",
        "const char* wdfFunctionName(std::size_t index) {",
        f"    return index < {count} ? kNames[index] : nullptr;",
        "}",
        "",
        "} // namespace dasa::core::driver",
        "",
    ]
    open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(f"wrote {count} entries to {out_path}")


if __name__ == "__main__":
    main()
